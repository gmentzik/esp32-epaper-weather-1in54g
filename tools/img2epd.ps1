<#
.SYNOPSIS
  Converts a picture into bottom_image.h / bottom_image.cpp for the bottom area of the
  weather screen (Waveshare 1.54" (G): black, white, yellow, red).

.DESCRIPTION
  The picture is scaled to fit Width x Height (default 200 x 94, the free bottom area),
  centred on white, and every pixel is mapped to the nearest of the 4 panel colours.
  The output uses the panel's own 2-bit colour codes (0 black, 1 white, 2 yellow, 3 red),
  4 pixels per byte, leftmost pixel in the top bits: the same layout as the sketch's image buffer.

  Works in Windows PowerShell 5.1 (uses the built-in System.Drawing), nothing to install.
  Best results come from simple, flat-colour pictures. Photos lose most detail with only 4 colours.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\img2epd.ps1 -In C:\pics\logo.png
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\img2epd.ps1 -Demo
  Draws the built-in sample picture instead of loading a file.
#>
param(
  [string]$In,
  [switch]$Demo,
  [int]$Width = 200,
  [int]$Height = 94,
  [string]$OutDir = (Join-Path $PSScriptRoot '..\ESP32_WEATHER_EPAPER')
)

Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'

if (-not $Demo -and -not $In) { throw 'Give -In <picture file> or -Demo.' }
if ($Width -gt 200 -or $Height -gt 94) { throw 'The bottom area is 200 x 94 px; use a smaller -Width / -Height.' }

$bmp = New-Object System.Drawing.Bitmap($Width, $Height)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.Clear([System.Drawing.Color]::White)

if ($Demo) {
  # Sample picture: frame, sun, mountains, text. No anti-aliasing, so only pure colours appear.
  $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::None
  $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
  $black = [System.Drawing.Brushes]::Black
  $g.FillEllipse([System.Drawing.Brushes]::Yellow, $Width - 52, 8, 34, 34)
  $mountains = [System.Drawing.Point[]]@(
    (New-Object System.Drawing.Point(0, ($Height - 1))),
    (New-Object System.Drawing.Point(45, 40)),
    (New-Object System.Drawing.Point(80, 70)),
    (New-Object System.Drawing.Point(120, 30)),
    (New-Object System.Drawing.Point(170, ($Height - 1)))
  )
  $g.FillPolygon($black, $mountains)
  $font = New-Object System.Drawing.Font('Arial', 11, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
  $g.DrawString('SAMPLE IMAGE', $font, [System.Drawing.Brushes]::Red, 6, 6)
  $g.DrawString('tools/img2epd.ps1', $font, $black, 6, 20)
  $g.DrawRectangle([System.Drawing.Pens]::Black, 0, 0, $Width - 1, $Height - 1)
  $source = 'built-in sample (-Demo)'
} else {
  $src = [System.Drawing.Image]::FromFile((Resolve-Path $In))
  $scale = [Math]::Min($Width / $src.Width, $Height / $src.Height)
  $w = [int]($src.Width * $scale); $h = [int]($src.Height * $scale)
  $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
  $g.DrawImage($src, [int](($Width - $w) / 2), [int](($Height - $h) / 2), $w, $h)
  $src.Dispose()
  $source = Split-Path $In -Leaf
}
$g.Dispose()

# Panel colours, index = colour code on the panel.
$palette = @(@(0, 0, 0), @(255, 255, 255), @(255, 255, 0), @(255, 0, 0))
$rowBytes = [int][Math]::Ceiling($Width / 4)
$data = New-Object byte[] ($rowBytes * $Height)
for ($y = 0; $y -lt $Height; $y++) {
  for ($x = 0; $x -lt $Width; $x++) {
    $c = $bmp.GetPixel($x, $y)
    $best = 0; $bestDist = [int]::MaxValue
    for ($i = 0; $i -lt 4; $i++) {
      $dr = $c.R - $palette[$i][0]; $dg = $c.G - $palette[$i][1]; $db = $c.B - $palette[$i][2]
      $dist = $dr * $dr + $dg * $dg + $db * $db
      if ($dist -lt $bestDist) { $bestDist = $dist; $best = $i }
    }
    if ($c.A -lt 128) { $best = 1 }   # transparent -> white
    $idx = $y * $rowBytes + [int][Math]::Floor($x / 4)
    $data[$idx] = $data[$idx] -bor ($best -shl (6 - 2 * ($x % 4)))
  }
}
$bmp.Dispose()

$header = @"
// Picture for the bottom area of the weather screen.
// Generated by tools/img2epd.ps1 from: $source. Do not edit by hand; run the script again.

#ifndef BOTTOM_IMAGE_INCLUDED
#define BOTTOM_IMAGE_INCLUDED

#define BOTTOM_IMAGE_W $Width
#define BOTTOM_IMAGE_H $Height

// 2 bits per pixel (0 black, 1 white, 2 yellow, 3 red), 4 pixels per byte,
// leftmost pixel in the top bits, $rowBytes bytes per row.
extern const unsigned char bottomImage[];

#endif
"@

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Picture for the bottom area of the weather screen.')
[void]$sb.AppendLine("// Generated by tools/img2epd.ps1 from: $source. Do not edit by hand; run the script again.")
[void]$sb.AppendLine('')
[void]$sb.AppendLine('#include "bottom_image.h"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine("const unsigned char bottomImage[$($data.Length)] = {   // $Width x $Height px")
for ($i = 0; $i -lt $data.Length; $i += 16) {
  $n = [Math]::Min(16, $data.Length - $i)
  $line = ($data[$i..($i + $n - 1)] | ForEach-Object { '0x{0:X2}' -f $_ }) -join ', '
  [void]$sb.AppendLine("  $line,")
}
[void]$sb.AppendLine('};')

$utf8 = New-Object System.Text.UTF8Encoding($false)
$outDirFull = (Resolve-Path $OutDir).Path
[System.IO.File]::WriteAllText((Join-Path $outDirFull 'bottom_image.h'), $header.Replace("`r`n", "`n") + "`n", $utf8)
[System.IO.File]::WriteAllText((Join-Path $outDirFull 'bottom_image.cpp'), $sb.ToString().Replace("`r`n", "`n"), $utf8)
Write-Host "Wrote bottom_image.h and bottom_image.cpp ($Width x $Height, $($data.Length) bytes) to $outDirFull"
